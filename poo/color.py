from enum import Enum

#Enum es un tipo de dato que representa un conjunto de constantes
class Color(Enum):
    RED: str = 'Red'
    YELLOW: str = 'Yellow'
    GREEN: str = 'Green'
    BLUE: str = 'Blue'
    PURPLE: str = 'Purple'
    ORANGE: str = 'Orange'
    PINK: str = 'Pink'
    BROWN: str = 'Brown'
    GRAY: str = 'Gray'
    BLACK: str = 'Black'
    WHITE: str = 'White'